import { describe, expect, it } from 'vitest'
import { readFileSync } from 'node:fs'
const read = (path) => readFileSync(new URL(`../../${path}`, import.meta.url), 'utf8')
const store = read('src/components/web/WebStore.jsx')
const header = read('src/components/web/WebHeader.jsx')
const directory = read('src/components/web/WebCommunity.jsx')
const support = read('src/components/web/WebSupportMessenger.jsx')
const banner = read('src/components/web/WebBlackFriday.jsx')
const styles = read('src/styles/web/platform-home-discover.css')
const routes = JSON.parse(read('vercel.json'))

describe('web Home / Discover / Support functional contract', () => {
  it('removes the sidebar and redundant Coins navigation, leaving Home and Discover', () => {
    expect(store).not.toContain('<WebSidebar')
    expect(store).not.toContain("import WebSidebar")
    expect(header).toContain('>Home</a>')
    expect(header).toContain('>Discover</a>')
    expect(header).not.toContain('>Coins</a>')
    expect(header).not.toContain('>Fame Coins</a>')
    expect(styles).toContain('.fv-platform-topnav { display:flex !important;')
  })
  it('keeps all three Black Friday offers on Home and separates regular packs to /coins', () => {
    expect(store).toContain('isHomePage && <WebBlackFridayBanner />')
    expect(store).toContain('<WebBlackFridayPreview')
    expect(store).toContain('isCoinsPage ? (')
    expect(store).toContain('id="coin-packs"')
    expect(banner).toContain('2026-12-07T20:56:27.556Z')
    expect(banner).toContain('href="/coins#coin-packs"')
    expect(store).toContain('onCheckout={startCheckout}')
  })
  it('Discover lists all public profiles by pages, including the current user', () => {
    expect(directory).toContain("supabase.from('profiles')")
    expect(directory).toContain("count: 'exact'")
    expect(directory).toContain('Load more members')
    expect(directory).not.toContain('RECOMMENDED_LIMIT')
    expect(directory).not.toContain('excludeUserId')
    expect(directory).not.toContain('.slice(0, 8)')
    expect(directory).toContain('window.location.assign(`/?profile=')
    expect(routes.rewrites).toEqual(expect.arrayContaining([{ source: '/discover', destination: '/index.html' }]))
  })
  it('the floating speech icon submits real support messages through existing protected backend', () => {
    expect(store).toContain('<WebSupportMessenger userId=')
    expect(support).toContain('name="message"')
    expect(support).toContain("supabase.from('beta_feedback').insert")
    expect(support).toContain('user_id: userId')
    expect(support).toContain("category = subject === 'Report a bug' ? 'bug' : 'other'")
    expect(support).toContain('Sign in to message support')
    expect(support).toContain('setSent(true)')
    expect(styles).toContain('#fameverse-beta-feedback { display: none !important; }')
  })
})
